// 本局已抽记录，避免重复
let drawn = {}

export function getLevels() {
    return LEVELS
}

export function setLevel(key) {
    if (LEVELS.some(l => l.key === key)) drawn = {}
    return key
}

export function resetDrawn() {
    drawn = {}
}

// 随机抽一条：level 分级，type 类型（可选），返回 { text, level, type }
export function draw({ level = 'normal', type = '' } = {}) {
    const bank = BANK[level]
    if (!bank) return null
    const types = type ? [type] : Object.keys(bank)
    // 该分级+类型下未抽过的条目
    let pool = []
    types.forEach(t => {
        const used = drawn[level + ':' + t] || []
        const rest = bank[t].filter((_, i) => !used.includes(i))
        pool = pool.concat(rest.map(text => ({ text, type: t })))
    })
    if (!pool.length) {
        // 全抽过了则重置该分级
        types.forEach(t => { drawn[level + ':' + t] = [] })
        types.forEach(t => {
            pool = pool.concat(bank[t].map(text => ({ text, type: t })))
        })
    }
    const pick = pool[Math.floor(Math.random() * pool.length)]
    const key = level + ':' + pick.type
    const idx = BANK[level][pick.type].indexOf(pick.text)
    drawn[key] = (drawn[key] || []).concat(idx)
    return {
        text: pick.text,
        level,
        type: TYPES.find(t => t.key === pick.type)?.name || pick.type
    }
}

// 按分级统计题库规模
export function bankSize() {
    return LEVELS.reduce((n, l) => {
        const b = BANK[l.key]
        return n + b.truth.length + b.dare.length + b.action.length
    }, 0)
}
